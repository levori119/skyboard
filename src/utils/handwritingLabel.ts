/**
 * תווית **כתב יד** של פ"מ על המפה - הלוגיקה הטהורה.
 *
 * מדמה את מה שהבקר כותב בצ'ינו על הסדק, ונקראת כיחידה אחת משמאל לימין:
 *
 * ```
 * או"ק · מספרי מטוסים · מקף · טייסת
 * ```
 *
 * | תווית | משמעות |
 * |-------|--------|
 * | `כידון1-105`   | כידון מספר 1 בטייסת 105 |
 * | `כידון1+2-105` | כידון מספרים 1+2 בטייסת 105 |
 * | `בננה(2)-105`  | בננה, כל המבנה, שמספר המטוסים בו 2 |
 * | `ע305(1)-142`  | ע305, כל המבנה, שמספר המטוסים בו 1 |
 *
 * **הסוגריים הן שמבדילות בין השניים:** פ"מ מפוצל מציג את מספרי המטוסים עצמם
 * (`1`, `1+2`), ומבנה שלם מציג את מספר המטוסים שבו בתוך סוגריים (`(2)`).
 *
 * ── למה זה לא "רק להדפיס מחרוזת" ──────────────────────────────────────────
 *
 * התווית אינה משפט אלא **קוד בעל סדר קבוע**, ואלגוריתם ה-bidi של הדפדפן לא
 * יודע את זה - הוא מסדר לפי כללי טקסט דו-לשוני ומקבל תוצאה הפוכה מהכוונה:
 *
 * | מה שכתוב | מה ש-bidi מרנדר | למה |
 * |----------|------------------|-----|
 * | `כידון1+2-105` בקונטיינר RTL | `1+2-105כידון` | או"ק עברי נזרק לקצה הימני |
 * | `ע305` ברצף אחד | `305ע` | ספרות אחרי אות עברית מקבלות רמה גבוהה יותר ומתהפכות |
 *
 * שני התיקונים משלימים זה את זה, ואף אחד מהם לבדו לא מספיק:
 *
 * 1. **הקונטיינר `direction:'ltr'` קבוע** (ולא `dir`) - כדי שהאו"ק יישב משמאל
 *    ומספרי המטוסים והטייסת מימינו, בעברית ובאנגלית כאחד.
 * 2. **{@link bidiRuns} + `<bdi>` לכל רצף** - הבידוד הופך כל רצף לאובייקט
 *    נייטרלי בעיני האלגוריתם, ולכן הסדר **הלוגי** בין הרצפים נשמר: `ע` ואז
 *    `305`. בתוך כל רצף ה-bidi ממשיך לעבוד כרגיל, ולכן מילה עברית שלמה
 *    (`כידון`) עדיין מרונדרת כמילה תקינה ולא הפוכה.
 */

/** רצף אותיות עבריות (יוניקוד 0590-05FF), או רצף של כל השאר. */
const HEB_RUN = /[\u0590-\u05FF]+|[^\u0590-\u05FF]+/g;

export interface HandwritingLabel {
  /** או"ק - מרונדר דרך {@link bidiRuns}. */
  name: string;
  /** מספרי המטוסים והטייסת - רצף אחד ב-`<bdi dir="ltr">`. */
  suffix: string;
}

/**
 * מפרק מחרוזת לרצפים עבריים ולא-עבריים, כדי שכל אחד ישב ב-`<bdi>` משלו
 * וסדרם הלוגי יישמר.
 *
 * - `'ע305'` -> `['ע', '305']` - כך `ע` יישב משמאל ו-`305` מימינו
 * - `'כידון'` -> `['כידון']` - מילה עברית בלבד אינה מפורקת, אחרת האותיות
 *   היו מתהפכות
 * - `'SKY01'` -> `['SKY01']`
 */
export function bidiRuns(s: string): string[] {
  if (!s) return [];
  // אין ספרות ואין לטינית - אין מה לבודד, וכל פירוק רק היה שובר את המילה.
  if (!/[0-9A-Za-z]/.test(s)) return [s];
  return s.match(HEB_RUN) ?? [s];
}

/**
 * בונה את שני חלקי התווית מתוך שדות הפ"מ.
 *
 * `aircraftIndices` מגיע מה-DB גם כמערך וגם כמחרוזת JSON, ולכן שתי הצורות
 * מטופלות כאן ולא באתר הקריאה.
 */
export function handwritingLabel(opts: {
  callSign: string;
  aircraftIndices?: number[] | string | null;
  numberOfFormation?: number | string | null;
  squadron?: string | null;
}): HandwritingLabel {
  let idx: unknown = opts.aircraftIndices;
  if (typeof idx === 'string') { try { idx = JSON.parse(idx); } catch { idx = null; } }
  const indices = Array.isArray(idx) && idx.length > 0 ? (idx as number[]) : null;
  const cnt = String(opts.numberOfFormation ?? '').trim();
  const sq = String(opts.squadron ?? '').trim();

  // מפוצל -> מספרי המטוסים עצמם, בלי סוגריים. מבנה שלם -> מספר המטוסים בסוגריים.
  const ac = indices
    ? [...indices].sort((x, y) => x - y).join('+')
    : (cnt ? `(${cnt})` : '');

  return { name: String(opts.callSign ?? ''), suffix: ac + (sq ? `-${sq}` : '') };
}
