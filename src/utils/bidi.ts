// בידוד דו-כיווני לטקסט שהוזן על ידי המשתמש (שם אזור, הערה, שם סגירה).
//
// שם כמו "61 צפון" מתחיל בספרה - תו "חלש" באלגוריתם הדו-כיווני של יוניקוד -
// ולכן סדר התצוגה שלו נקבע לפי כיוון הבסיס של ההקשר:
//   כיוון בסיס RTL  → מוצג "61 צפון"  (כפי שהוזן)
//   כיוון בסיס LTR  → מוצג "צפון 61"  (הפוך)
// אזור המפה בעמדה יושב בתוך מיכל LTR מכוון (סדר העמודות), וגם כשה-UI באנגלית
// שורש המסמך הוא LTR - ולכן שמות אזורים הוצגו הפוכים על המפה ובתוויות שעליה.
//
// FSI/PDI הם התקן היוניקודי של dir="auto": כיוון הבסיס נקבע לפי האות החזקה
// הראשונה במחרוזת עצמה (עברית → RTL, לטינית → LTR), והמחרוזת מבודדת מהטקסט
// שסביבה. זו הדרך היחידה שעובדת גם ב-SVG <text>, שבו אין תמיכה במאפיין dir.
// התווים בלתי נראים ורוחבם אפס - הם לא משנים מרכוז (textAnchor="middle").
export const FSI = '⁨'; // FIRST STRONG ISOLATE
export const PDI = '⁩'; // POP DIRECTIONAL ISOLATE

export function bidiAuto(value: string | null | undefined): string {
  const s = value == null ? '' : String(value);
  if (s === '') return ''; // כדי ש-filter(Boolean) על תוויות מורכבות ימשיך לעבוד
  if (s.startsWith(FSI) && s.endsWith(PDI)) return s; // אידמפוטנטי
  return FSI + s + PDI;
}
