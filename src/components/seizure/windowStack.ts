/**
 * **סדר הערימה של חלונות ההלאמה** - הליבה הטהורה.
 *
 * שלושת החלונות (פרטים · אישורי עמדות · מפת היוצר) צפים באותו אזור מסך. עם
 * z-index קבוע לכל אחד תמיד אותו חלון מנצח, ולכן "אישורי עמדות" שנפתח מתוך
 * חלון הפרטים נצבע **מתחתיו** - והפקח רואה לחיצה שלא עשתה כלום.
 *
 * במקום זה, סדר לפי **מי נגע אחרון**: רשימה מהאחורי לקדמי, וכל פתיחה או
 * לחיצה מקפיצה מפתח לסופה.
 *
 * הליבה כאן ולא ב-`useState` שבמסך כדי שתהיה בת-בדיקה: זו לוגיקה של סדר,
 * ובדיקה שלה דרך DOM הייתה בודקת את React ולא את הכלל.
 */

/** מתחת להתראה המתפרצת (10600) ולטופס ההגדרה (10700), מעל סרגלי המפה. */
export const SEIZURE_WIN_Z_BASE = 9600;

/**
 * מקפיץ מפתח לראש הערימה. מחזיר את **אותה** רשימה כשהמפתח כבר בראש, כדי
 * ש-`setState` יזהה זהות ולא ירנדר מחדש בכל לחיצה על חלון שכבר קדמי.
 */
export function raiseWindow(order: string[], key: string): string[] {
  if (order[order.length - 1] === key) return order;
  return [...order.filter(k => k !== key), key];
}

/** ה-z-index של חלון לפי מקומו. חלון שטרם נגעו בו יושב על הבסיס. */
export function windowZ(order: string[], key: string): number {
  return SEIZURE_WIN_Z_BASE + order.indexOf(key) + 1;
}
